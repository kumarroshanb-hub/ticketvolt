// ============================================
// AVAILABLE ACTIONS — single source of truth
// ============================================
export const getAvailableActions = (booking, { isRegularUser }) => {
    const status = booking?.status;
    const isCompleted = status === BOOKING_STATUS.COMPLETED;
    const isCancelled = status === BOOKING_STATUS.CANCELLED;
    const isRefunded = status === BOOKING_STATUS.REFUNDED;
    const isReadonly = isCompleted || isCancelled || isRefunded;

    const canViewETicket =
        status === BOOKING_STATUS.CONFIRMED ||
        status === BOOKING_STATUS.PAID ||
        status === BOOKING_STATUS.COMPLETED;

    const base = {
        canView: true,
        canViewETicket,
        canSendEmail: canViewETicket,
        isReadonly,
    };

    if (isRegularUser) {
        return {
            ...base,
            canManage: false,
            canMarkPayment: false,
            canConfirmPayment: false,
            canIssueTickets: false,
            canRegenerateQR: false,
            canCancel: false,
            canRefund: false,
        };
    }

    return {
        ...base,
        canManage: true,
        canMarkPayment: status === BOOKING_STATUS.PENDING,
        canConfirmPayment: status === BOOKING_STATUS.PENDING,
        canIssueTickets: status === BOOKING_STATUS.PAID,
        canRegenerateQR:
            status === BOOKING_STATUS.PAID || status === BOOKING_STATUS.CONFIRMED,
        canCancel: !isReadonly && status !== BOOKING_STATUS.CANCELLED,
        canRefund:
            status === BOOKING_STATUS.PAID || status === BOOKING_STATUS.CONFIRMED,
    };
};